#!/usr/bin/env python3
"""Embed individually reviewed, unmodified brand assets; no network at build/run time.

The review covers a specific use, not an open-source license for the trademarks.
An absent permission, changed file or unsafe SVG fails the build.
"""

import base64
import hashlib
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRANDS = ROOT / "packaging" / "brands"


def reviewed_brands():
    return json.loads((BRANDS / "review.json").read_text(encoding="utf-8"))["brands"]


def asset_bytes(name, info):
    if info.get("status") != "enabled":
        raise ValueError(f"{name}: no documented permission for this use")
    for field in ("terms_url", "reviewed", "decision", "owner", "attribution", "asset_url", "homepage"):
        if not info.get(field):
            raise ValueError(f"{name}: missing {field}")
    if info.get("asset") != name + ".svg":
        raise ValueError(f"{name}: invalid asset filename")
    data = (BRANDS / info["asset"]).read_bytes()
    if hashlib.sha256(data).hexdigest() != info.get("asset_sha256"):
        raise ValueError(f"{name}: original asset changed; review required")
    svg = ET.fromstring(data)
    if svg.tag != "{http://www.w3.org/2000/svg}svg":
        raise ValueError(f"{name}: not an SVG")
    for el in svg.iter():
        if el.tag.rsplit("}", 1)[-1] in {"script", "foreignObject", "image", "a"}:
            raise ValueError(f"{name}: active/external SVG content")
        for key, value in el.attrib.items():
            if key.lower().startswith("on") or (key.endswith("href") and not value.startswith("#")):
                raise ValueError(f"{name}: active/external SVG attribute")
    return data


def render():
    icons = {}
    for name, info in sorted(reviewed_brands().items()):
        if info["status"] == "enabled":
            icons[name] = {"title": info["title"], "url": info["homepage"],
                           "src": "data:image/svg+xml;base64," + base64.b64encode(asset_bytes(name, info)).decode()}
    return ("// Generated by tools/make_service_icons.py; see packaging/brands/review.json.\n"
            "// Original brand assets under their individual usage terms, not MIT or CC0.\n"
            f"const SERVICE_ICONS = {json.dumps(icons, separators=(',', ':'))};\n")


def main():
    target = ROOT / "static" / "service-icons.js"
    content = render()
    if "--check" in sys.argv:
        if target.read_text(encoding="utf-8") != content:
            raise SystemExit("service-icons.js differs from reviewed assets; regenerate it")
    else:
        target.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
