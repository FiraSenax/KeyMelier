// First supported language from a list like ["de-DE", "en-US"]
function pickLanguage(candidates) {
  for (const c of candidates || []) {
    const code = String(c).toLowerCase().split(/[-_]/)[0];
    if (STRINGS[code]) return code;
  }
  return 'en';
}

let SYSTEM_LANG = pickLanguage(navigator.languages || [navigator.language]);
let LANG_CHOICE = '';  // '' = follow the system, otherwise a language code
let LANG = SYSTEM_LANG;

function t(key, vars = {}) {
  const s = STRINGS[LANG]?.[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

function setLang(lang) {
  LANG = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = LANG;
  applyI18n();
}

// Fill every element carrying data-i18n (text) or data-i18n-title (tooltip)
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}
